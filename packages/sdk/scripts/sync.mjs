// Copies the contract ABIs and the deployment record from the repository root into src/generated.
// The root files are the source of truth and are only ever read here. The package keeps its own
// copy so it can be published and used without the rest of the repo.
//
//   node scripts/sync.mjs           rewrite src/generated
//   node scripts/sync.mjs --check   exit 1 if src/generated is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(here, "..", "src", "generated");
const check = process.argv.includes("--check");

const abis = [
  ["lensAbi", "PositionLens"],
  ["factoryAbi", "TrozuFactory"],
  ["marketAbi", "TrozuMarket"],
  ["nftAbi", "TrozuNFT"],
  ["vaultAbi", "TrozuVault"],
];

const header = "// generated by scripts/sync.mjs from the repository root, do not edit by hand\n";

function abiFile() {
  let s = header;
  for (const [name, file] of abis) {
    const abi = JSON.parse(readFileSync(join(root, "abi", "v2", `${file}.json`), "utf8"));
    s += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  }
  return s;
}

function deploymentFile() {
  const d = JSON.parse(readFileSync(join(root, "web", "src", "config", "deployment.v2.json"), "utf8"));
  // the abi paths only mean something inside the repo
  delete d.abi;
  return `${header}\nexport const matsnetDeployment = ${JSON.stringify(d, null, 2)} as const;\n`;
}

const files = { "abis.ts": abiFile(), "deployment.ts": deploymentFile() };
let stale = false;
for (const [name, text] of Object.entries(files)) {
  const path = join(out, name);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== text) {
      console.error(`${name} is out of date, run npm run sync`);
      stale = true;
    }
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${name}`);
  }
}
if (stale) process.exit(1);
