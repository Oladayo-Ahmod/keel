#!/usr/bin/env bash
# Regenerates src/abi/keel.ts from the compiled contracts. Run from the repo root
# after `forge build`:  web/scripts/generate-abi.sh
set -euo pipefail
out=web/src/abi/keel.ts
{
  echo "// Generated by web/scripts/generate-abi.sh from forge inspect. Do not edit."
  for c in PositionFactory PositionVault PositionNFT PositionLens; do
    name="$(echo "${c:0:1}" | tr 'A-Z' 'a-z')${c:1}Abi"
    printf 'export const %s = %s as const

' "$name" "$(forge inspect "$c" abi --json)"
  done
} > "$out"
