// Writes src/abi/trozu.ts from compiled forge artifacts for the wave 2 contracts.
//   node scripts/generate-abi-v2.mjs <path to the forge out/ directory>
// Run it after `forge build` on the commit that is being deployed, then commit the result.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = process.argv[2];
if (!out) {
  console.error("usage: node scripts/generate-abi-v2.mjs <forge out dir>");
  process.exit(1);
}
const names = ["TrozuMarket", "TrozuVault", "TrozuNFT", "TrozuFactory"];
let src = "// Generated by web/scripts/generate-abi-v2.mjs from forge artifacts. Do not edit.\n";
for (const c of names) {
  const abi = JSON.parse(readFileSync(join(out, `${c}.sol`, `${c}.json`), "utf8")).abi;
  src += `\nexport const ${c[0].toLowerCase()}${c.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(new URL("../src/abi/trozu.ts", import.meta.url), src);
console.log("wrote src/abi/trozu.ts");
